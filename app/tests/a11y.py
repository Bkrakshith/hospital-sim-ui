"""Accessibility pass for the G1 iPad app.

1. WCAG contrast of every foreground/background token pair the UI uses, both themes (from css/tokens.css).
2. Touch targets and accessible names, from docs/a11y_targets.json (written by tests/screens.py).

    python hospital-sim-ui/app/tests/a11y.py            -> prints tables, writes docs/a11y_report.md, exits 1 on a failure
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
css = open(os.path.join(APP, 'css', 'tokens.css')).read()


def block(sel):
    out = {}
    for m in re.finditer(re.escape(sel) + r'\s*\{([^}]*)\}', css):
        for k, v in re.findall(r'(--[\w-]+):\s*([^;]+);', m.group(1)):
            out[k] = v.strip()
    return out


light = block(':root')
dim = {**light, **block(':root[data-theme="dim"]')}


def resolve(theme, v):
    while v.startswith('var('):
        v = theme[v[4:-1].strip()]
    return v


def rgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def lum(c):
    f = lambda x: x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4  # noqa: E731
    r, g, b = map(f, c)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(a, b):
    la, lb = lum(rgb(a)), lum(rgb(b))
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


WHITE = '#FFFFFF'
# (foreground, background, kind) kind: text (4.5) | large (3.0, >= 22 pt bold / status words) | ui (3.0, icons/outlines)
PAIRS = [
    ('--text', '--bg', 'text'), ('--text', '--surface', 'text'), ('--text', '--surface-2', 'text'), ('--text', '--surface-3', 'text'),
    ('--text-2', '--bg', 'text'), ('--text-2', '--surface', 'text'), ('--text-2', '--surface-2', 'text'),
    ('--border-strong', '--surface', 'ui'), ('--border-strong', '--bg', 'ui'),
    ('--robot-driving', '--bg', 'text'), ('--robot-driving', '--surface', 'text'), ('--robot-driving', '--robot-driving-soft', 'text'),
    ('--person-driving', '--surface', 'text'), ('--person-driving', '--person-driving-soft', 'ui'),
    ('--standby', '--surface', 'text'), ('--off', '--surface', 'ui'),
    ('--ok', '--bg', 'text'), ('--ok', '--surface', 'text'), ('--ok', '--ok-soft', 'text'),
    ('--alarm-high', '--bg', 'text'), ('--alarm-high', '--surface', 'text'), ('--alarm-high', '--alarm-high-soft', 'text'),
    ('--alarm-med', '--surface', 'text'), ('--alarm-med', '--alarm-med-soft', 'text'), ('--text', '--alarm-med-soft', 'text'),
    ('--on-alarm-med', '--alarm-med-fill', 'text'),
    ('--alarm-low', '--surface', 'text'), ('--alarm-low', '--alarm-low-soft', 'ui'), ('--text', '--alarm-low-soft', 'text'),
    (WHITE, '--alarm-high-fill', 'text'), (WHITE, '--fill-robot', 'text'), (WHITE, '--fill-person', 'text'),
    (WHITE, '--fill-standby', 'text'), (WHITE, '--fill-ok', 'text'),
    ('--text-2', '--map-bg', 'text'), ('--robot-driving', '--map-free', 'ui'), ('--map-occ', '--map-free', 'ui'),
]
MIN = {'text': 4.5, 'large': 3.0, 'ui': 3.0}

rows, fails = [], 0
for theme_name, theme in (('Light', light), ('Theatre dim', dim)):
    for fg, bg, kind in PAIRS:
        f = fg if fg.startswith('#') else resolve(theme, theme[fg])
        b = resolve(theme, theme[bg])
        r = ratio(f, b)
        ok = r >= MIN[kind]
        fails += not ok
        rows.append((theme_name, fg, bg, f, b, r, kind, ok))

md = ['# Accessibility report (generated by tests/a11y.py)', '', '## Contrast (WCAG 2.x)', '',
      '| Theme | Foreground | Background | Ratio | Needs | Result |', '|---|---|---|---|---|---|']
for t, fg, bg, f, b, r, kind, ok in rows:
    md.append(f'| {t} | `{fg}` {f} | `{bg}` {b} | {r:.2f}:1 | {MIN[kind]}:1 ({kind}) | {"pass" if ok else "**FAIL**"} |')

# touch targets
tpath = os.path.join(APP, 'docs', 'a11y_targets.json')
tfails, noname, total = [], [], 0
if os.path.exists(tpath):
    audit = json.load(open(tpath))
    for screen, items in audit.items():
        for it in items:
            total += 1
            w, h = it['w'], it['h']
            need = 44
            if it['zone'] == 'safety' and 'STOP' in it['name'].upper() and 'stop' in it['name'].lower():
                need = 88
            elif it['role'] == 'clinical' and it['zone'] in ('main', 'sheet') and it['tag'] != 'INPUT':
                need = 64
            if min(w, h) < need:
                tfails.append((screen, it['name'] or it['cls'], w, h, need, it['zone']))
            if not it['name']:
                noname.append((screen, it['tag'], it['cls']))
md += ['', '## Touch targets', '', f'{total} visible controls on the audited screens (Light, landscape). Rule: Stop >= 88 pt, clinical content >= 64 pt, everything else >= 44 pt (05 §5).', '']
if tfails:
    md += ['| Screen | Control | Size | Needs | Zone |', '|---|---|---|---|---|'] + [f'| {s} | {n} | {w}x{h} | {nd} | {z} |' for s, n, w, h, nd, z in tfails]
else:
    md.append('All pass.')
md += ['', '## Accessible names (VoiceOver)', '']
md += [f'- {s}: `{t}` `{c}` has no accessible name' for s, t, c in noname] if noname else ['Every visible control has an accessible name (aria-label or text).']
open(os.path.join(APP, 'docs', 'a11y_report.md'), 'w').write('\n'.join(md) + '\n')
print('\n'.join(md))
print(f'\ncontrast fails: {fails} · target fails: {len(tfails)} · unnamed controls: {len(noname)}')
sys.exit(1 if fails or tfails or noname else 0)
